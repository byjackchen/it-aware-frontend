'use client';

import { useState, useTransition, useMemo } from 'react';
import { useRouter } from 'next/navigation';
import { Save, X, Loader2 } from 'lucide-react';
import { useTranslations } from 'next-intl';
import { createPermission } from '../actions';

export function PermissionForm() {
  const t = useTranslations('Security');
  const router = useRouter();
  const [domain, setDomain] = useState('');
  const [resource, setResource] = useState('');
  const [action, setAction] = useState('');
  const [description, setDescription] = useState('');
  const [isPending, startTransition] = useTransition();
  const [error, setError] = useState<string | null>(null);

  // Generate permission code preview
  const previewCode = useMemo(() => {
    if (!domain && !resource && !action) return '---';
    return `${domain || '---'}:${resource || '---'}:${action || '---'}`;
  }, [domain, resource, action]);

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    const formData = new FormData();
    formData.set('domain', domain);
    formData.set('resource', resource);
    formData.set('action', action);
    formData.set('description', description);

    startTransition(async () => {
      const result = await createPermission(formData);
      if (result?.error) {
        setError(result.error);
      }
    });
  };

  const handleCancel = () => {
    router.push('/security/permissions');
  };

  return (
    <div className="flex flex-col h-full">
      {/* Header */}
      <div className="p-4 border-b theme-border-panel flex items-center justify-between">
        <h2 className="text-lg font-semibold theme-text-primary">{t('permissions.createPermission')}</h2>
        <div className="flex items-center gap-2">
          <button
            onClick={handleCancel}
            className="flex items-center gap-2 px-3 py-1.5 rounded-lg theme-btn-neutral"
          >
            <X className="w-4 h-4" />
            {t('common.cancel')}
          </button>
          <button
            onClick={handleSubmit}
            disabled={isPending || !domain || !resource || !action}
            className="flex items-center gap-2 px-3 py-1.5 rounded-lg bg-blue-500/20 hover:bg-blue-500/30 text-blue-400 transition-colors disabled:opacity-50"
          >
            {isPending ? <Loader2 className="w-4 h-4 animate-spin" /> : <Save className="w-4 h-4" />}
            {t('common.create')}
          </button>
        </div>
      </div>

      {/* Content */}
      <form onSubmit={handleSubmit} className="flex-1 p-4 overflow-y-auto">
        {error && (
          <div className="mb-4 p-3 rounded-lg bg-red-500/10 border border-red-500/20 text-red-400 text-sm">
            {error}
          </div>
        )}

        <div className="space-y-4">
          {/* Permission Code Preview */}
          <div>
            <label className="block text-sm font-medium mb-1 theme-text-label">{t('permissions.permissionCodePreview')}</label>
            <div className="px-3 py-2 rounded-lg font-mono text-sm theme-input-readonly theme-text-muted">
              {previewCode}
            </div>
            <p className="mt-1 text-xs theme-text-muted">{t('permissions.autoGenerated')}</p>
          </div>

          {/* Domain, Resource, Action */}
          <div className="grid grid-cols-3 gap-4">
            <div>
              <label className="block text-sm font-medium mb-1 theme-text-label">
                {t('permissions.domain')} <span className="text-red-400">*</span>
              </label>
              <input
                type="text"
                value={domain}
                onChange={(e) => setDomain(e.target.value)}
                className="w-full px-3 py-2 rounded-lg text-sm theme-input"
                placeholder={t('permissions.domainPlaceholder')}
                required
              />
            </div>
            <div>
              <label className="block text-sm font-medium mb-1 theme-text-label">
                {t('permissions.resource')} <span className="text-red-400">*</span>
              </label>
              <input
                type="text"
                value={resource}
                onChange={(e) => setResource(e.target.value)}
                className="w-full px-3 py-2 rounded-lg text-sm theme-input"
                placeholder={t('permissions.resourcePlaceholder')}
                required
              />
            </div>
            <div>
              <label className="block text-sm font-medium mb-1 theme-text-label">
                {t('permissions.action')} <span className="text-red-400">*</span>
              </label>
              <input
                type="text"
                value={action}
                onChange={(e) => setAction(e.target.value)}
                className="w-full px-3 py-2 rounded-lg text-sm theme-input"
                placeholder={t('permissions.actionPlaceholder')}
                required
              />
            </div>
          </div>

          {/* Description */}
          <div>
            <label className="block text-sm font-medium mb-1 theme-text-label">{t('common.description')}</label>
            <textarea
              value={description}
              onChange={(e) => setDescription(e.target.value)}
              rows={3}
              className="w-full px-3 py-2 rounded-lg text-sm resize-none theme-input"
              placeholder={t('common.descriptionPlaceholder')}
            />
          </div>
        </div>
      </form>
    </div>
  );
}
